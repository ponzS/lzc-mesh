// Shared clipboard on macOS: polls NSPasteboard's change count (there is no
// change notification) and writes text that arrives from other devices.
import AppKit

final class Clipboard {
    weak var hub: Hub?
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    private var lastText: String?
    static let maxBytes = 256 * 1024
    // Password managers mark secrets with these types (nspasteboard.org); never forward them.
    private let skipTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        let s = AppState.shared
        guard s.clipboardEnabled, s.hubConnected else { return }
        let types = Set((pb.types ?? []).map { $0.rawValue })
        guard types.isDisjoint(with: skipTypes), let text = pb.string(forType: .string), !text.isEmpty, text != lastText else { return }
        guard text.utf8.count <= Clipboard.maxBytes else { s.log("剪贴板文本超过 256 KB，未同步"); return }
        lastText = text
        hub?.send(["t": "clipboard", "text": text])
        s.log("已同步本机剪贴板（\(text.utf8.count) 字节）")
    }

    func set(_ text: String, from: String) {
        guard AppState.shared.clipboardEnabled, !text.isEmpty, text != lastText else { return }
        lastText = text
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        lastCount = pb.changeCount  // our own write must not be sent back
        AppState.shared.log("已接收来自 \(from.isEmpty ? "其他设备" : from) 的剪贴板（\(text.utf8.count) 字节）")
    }
}
